"""
run_cleaner_eval.py
Cleaner Agent Evaluation Harness:
Evaluates the Cleaner LLM agent against synthetic corrupted datasets generated by
make_dirty_dataset, and compares performance against a deterministic non-LLM baseline.

Features:
- Multi-seed error injection evaluation (--seeds 42 43 44).
- Head-to-head comparison with baseline_clean.
- Rigorous metrics via cleaner_metrics (row preservation, missing values, text,
  negatives, numbers as text, damage, statistical drift).
- Per-seed resumability via seeds.jsonl.
- Token budget enforcement via TokenBudget with clean pause.
- Graceful exit on LLM errors (LLMUnavailableError, LLMConfigError, BudgetExceeded).
- Comprehensive JSON and Markdown reporting (summary.json and summary.md).

Usage:
    python -m eval.run_cleaner_eval [--seeds 42 43 44] [--max-tokens N] [--run-dir PATH]
"""

