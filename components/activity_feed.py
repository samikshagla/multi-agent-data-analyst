"""
components/activity_feed.py
Streamlit component for the live agent activity timeline feed.
Displays incoming pipeline events in a scrollable 320px container with
agent icons, timestamps, color-coded types, and highlighted retry badges.
"""

from typing import Any
import streamlit as st


def render_feed(placeholder: Any, events_html_list: list[str]) -> None:
    """
    Renders the live activity timeline feed inside a Streamlit placeholder.

    Args:
        placeholder: Streamlit placeholder (e.g. st.empty()).
        events_html_list: List of HTML snippets generated by ui_state.event_to_html.
    """
    with placeholder.container():
        st.markdown("#### ⚡ Live Agent Activity Feed")

        if not events_html_list:
            feed_inner = (
                '<div class="feed-empty-message">'
                'Agents will report here once you start the analysis'
                '</div>'
            )
        else:
            feed_inner = "\n".join(events_html_list)

        html_content = f"""
<div class="activity-feed-container" id="activity-feed-box">
    {feed_inner}
</div>
<script>
    var feedBox = document.getElementById("activity-feed-box");
    if (feedBox) {{
        feedBox.scrollTop = feedBox.scrollHeight;
    }}
</script>
"""
        st.markdown(html_content, unsafe_allow_html=True)
