"""
state.py
State Definitions: Defines the shared workflow state (AgentState) passed
between agents in the LangGraph data analysis pipeline, along with the
factory function new_state() to initialize default execution states.
"""

from typing import TypedDict, Any


class AgentState(TypedDict):
    """
    Shared state schema across all agents in the Multi-Agent Data Analyst graph.

    Fields:
        raw_df_path: Path to the original raw CSV uploaded by the user.
        clean_df_path: Path to the cleaned CSV file produced by the Cleaner agent.
        profile: Compact profile dictionary produced by the Profiler tool.
        cleaning_log: List of actions and transformations applied during data cleaning.
        questions: List of analytical business questions generated for analysis.
        analysis_results: List of execution outputs from Analyst agent
                          (each item contains: question, code, result, status).
        charts: List of chart specifications or Plotly JSON structures generated by Visualizer.
        review_feedback: List of validation checks and critique feedback from Reviewer agent.
        review_report: Full log of all pass/fail audit verdicts and warnings from Reviewer agent.
        caught_errors: List of exceptions or errors caught during agent code execution.
        retry_count: Number of review/retry iterations between Reviewer and Analyst (max 3).
        final_report: Final synthesized report with findings, metrics, and chart references.
        events: Event trail for live activity feed / timeline tracking in the UI.
        run_stats: Performance and usage metrics (execution time, LLM calls, tokens, retries).
        rerun_ids: Analysis result IDs re-executed by Analyst following review feedback.
    """
    raw_df_path: str
    clean_df_path: str
    profile: dict[str, Any]
    cleaning_log: list[str]
    questions: list[str]
    analysis_results: list[dict[str, Any]]
    charts: list[dict[str, Any]]
    review_feedback: list[dict[str, Any]]
    review_report: list[dict[str, Any]]
    caught_errors: list[dict[str, Any]]
    retry_count: int
    final_report: str
    events: list[dict[str, Any]]
    run_stats: dict[str, Any]
    rerun_ids: list[int]


def new_state(raw_df_path: str) -> AgentState:
    """
    Creates and returns a new AgentState initialized with sensible empty defaults.

    Args:
        raw_df_path (str): File path to the raw dataset CSV.

    Returns:
        AgentState: State dictionary with default empty values and retry_count 0.
    """
    return {
        "raw_df_path": raw_df_path,
        "clean_df_path": "",
        "profile": {},
        "cleaning_log": [],
        "questions": [],
        "analysis_results": [],
        "charts": [],
        "review_feedback": [],
        "review_report": [],
        "caught_errors": [],
        "retry_count": 0,
        "final_report": "",
        "events": [],
        "run_stats": {},
        "rerun_ids": [],
    }
