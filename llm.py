"""
llm.py
Initializes the Gemini model using langchain-google-genai and provides
a helper function to send prompts and receive responses as plain strings.
"""

import os
import time
from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI

# Load environment variables from .env file
load_dotenv()


def call_llm(prompt: str) -> str:
    """
    Calls the Gemini LLM with a given prompt using GEMINI_API_KEY from .env.
    Always returns a plain string, extracting text blocks if the response
    contains multi-part content blocks.

    Args:
        prompt (str): The input text prompt to send to the Gemini model.

    Returns:
        str: The plain text response generated by Gemini.

    Raises:
        ValueError: If GEMINI_API_KEY is not found or has default placeholder value.
        Exception: If the API call fails during execution.
    """
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key or api_key.strip() == "your_key_here":
        raise ValueError(
            "GEMINI_API_KEY is missing or not set in the .env file. "
            "Please create a .env file from .env.example and add your valid Gemini API key."
        )

    model_name = os.getenv("GEMINI_MODEL", "gemini-3.8-flash")
    max_retries = int(os.getenv("MAX_RETRIES", "3"))

    last_exception = None
    for attempt in range(max_retries):
        try:
            # Initialize Gemini chat model via LangChain
            llm = ChatGoogleGenerativeAI(
                model=model_name,
                google_api_key=api_key,
                temperature=0.2,
                max_retries=max_retries,
            )
            response = llm.invoke(prompt)
            content = response.content

            # 1. If response.content is already a string
            if isinstance(content, str):
                result_text = content
            # 2. If it is a list of blocks, join 'text' from text-type blocks
            # and ignore everything else (extras, signatures, thinking blocks)
            elif isinstance(content, list):
                text_parts = []
                for block in content:
                    if isinstance(block, dict):
                        if block.get("type") == "text" and "text" in block:
                            text_parts.append(str(block["text"]))
                    elif hasattr(block, "type") and getattr(block, "type") == "text":
                        if hasattr(block, "text"):
                            text_parts.append(str(block.text))
                    elif isinstance(block, str):
                        text_parts.append(block)
                result_text = "".join(text_parts)
            else:
                result_text = str(content)

            # 3. Strip leading/trailing whitespace from the final string
            return result_text.strip()

        except Exception as e:
            last_exception = e
            print(f"Attempt {attempt + 1}/{max_retries} failed: {e}")
            if attempt < max_retries - 1:
                time.sleep(2 ** attempt)
            else:
                print(f"Error during Gemini LLM call after {max_retries} attempts: {e}")
                raise last_exception


if __name__ == "__main__":
    # Standalone sanity test to verify response and type
    print("Testing call_llm()...")
    try:
        result = call_llm("Respond with 'Gemini connection successful!' if you can read this.")
        print("Response received:")
        print(result)
        print("Type of response:")
        print(type(result))
    except Exception as err:
        print(f"Test encountered an issue: {err}")
